def format_fasta(header: str, seq: str) -> str:
    lines = [f">{header}"]
    for i in range(0, len(seq), 80):
        lines.append(seq[i:i+80])
    return "\n".join(lines) + "\n"

def main():
    root = Path(__file__).resolve().parent.parent
    dirs = [
        root / "test_sequences",
        root / "frontend" / "public" / "test_sequences"
    ]
    for d in dirs:
        d.mkdir(parents=True, exist_ok=True)

    print(f"Generating {len(BENCHMARKS)} benchmark FASTA files...")
    manifest = []
    for item in BENCHMARKS:
        seq = item["sequence"].strip().upper()
        assert len(seq) % 3 == 0, f"Error: {item['filename']} length not div by 3!"
        assert seq.startswith("ATG"), f"Error: {item['filename']} does not start with ATG!"
        content = format_fasta(item["header"], seq)
        
        for d in dirs:
            filepath = d / item["filename"]
            with open(filepath, "w", encoding="utf-8") as f:
                f.write(content)

        manifest.append({
            "filename": item["filename"],
            "gene": item["gene"],
            "lengthBp": len(seq),
            "codons": len(seq) // 3,
            "header": item["header"],
        })
        print(f"  + {item['filename']} ({len(seq)} bp, {len(seq)//3} codons)")

    # Save manifest.json in test_sequences
    import json
    for d in dirs:
        with open(d / "manifest.json", "w", encoding="utf-8") as f:
            json.dump(manifest, f, indent=2)

    print(f"Generated {len(BENCHMARKS)} test FASTA files and manifest in test_sequences/ & frontend/public/test_sequences/")

if __name__ == "__main__":
    main()
